// =================================================================
//   I18n runtime
// =================================================================

(function () {
  const STORAGE_KEY = 'rosso.lang';
  const DEFAULT_LANG = 'en';
  const SUPPORTED = ['en', 'fr'];

  function getInitialLang() {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    return DEFAULT_LANG;
  }

  function t(key, lang) {
    const dict = window.I18N[lang] || window.I18N[DEFAULT_LANG];
    return dict[key] != null ? dict[key] : (window.I18N[DEFAULT_LANG][key] || '');
  }

  function applyLang(lang) {
    if (!SUPPORTED.includes(lang)) lang = DEFAULT_LANG;
    document.documentElement.lang = lang;
    document.documentElement.dataset.lang = lang;

    // textContent (no HTML)
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const v = t(key, lang);
      if (v) el.textContent = v;
    });

    // innerHTML (with HTML)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const v = t(key, lang);
      if (v) el.innerHTML = v;
    });

    // href routing (legal pages)
    document.querySelectorAll('[data-i18n-href]').forEach(el => {
      const key = el.getAttribute('data-i18n-href');
      const v = t(key, lang);
      if (v) el.setAttribute('href', v);
    });

    // Update lang switcher visual state
    document.querySelectorAll('.lang-switch button').forEach(btn => {
      btn.classList.toggle('active', btn.dataset.lang === lang);
      btn.setAttribute('aria-pressed', btn.dataset.lang === lang ? 'true' : 'false');
    });

    localStorage.setItem(STORAGE_KEY, lang);
  }

  // Expose
  window.setLang = applyLang;
  window.getLang = () => document.documentElement.dataset.lang || DEFAULT_LANG;

  // Run on DOM ready
  function init() {
    // Static-language legal pages declare their own page lang.
    // They expose a sibling URL via `data-en-href` / `data-fr-href` on <body>.
    const body = document.body;
    const isStaticLangPage = body.dataset.enHref || body.dataset.frHref;

    if (isStaticLangPage) {
      // This page has its own fixed language — don't translate content.
      // Lang switcher should navigate to the sibling file.
      const pageLang = document.documentElement.lang || DEFAULT_LANG;
      localStorage.setItem(STORAGE_KEY, pageLang);
      document.querySelectorAll('.lang-switch button').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === pageLang);
        btn.setAttribute('aria-pressed', btn.dataset.lang === pageLang ? 'true' : 'false');
        btn.addEventListener('click', (e) => {
          e.preventDefault();
          const target = btn.dataset.lang;
          if (target === pageLang) return;
          const dest = target === 'en' ? body.dataset.enHref : body.dataset.frHref;
          if (dest) {
            localStorage.setItem(STORAGE_KEY, target);
            window.location.href = dest;
          }
        });
      });
      // Still apply href routing on footer sublinks
      const lang = pageLang;
      document.querySelectorAll('[data-i18n-href]').forEach(el => {
        const key = el.getAttribute('data-i18n-href');
        const v = t(key, lang);
        if (v) el.setAttribute('href', v);
      });
      return;
    }

    // Standard page (homepage): full inline i18n
    applyLang(getInitialLang());

    document.querySelectorAll('.lang-switch button').forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        applyLang(btn.dataset.lang);
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
